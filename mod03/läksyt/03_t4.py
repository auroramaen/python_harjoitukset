# Kysytään kolme kokonaislukua
luku1 = int(input('Anna luku: '))
luku2 = int(input('Anna toinen luku: '))
luku3 = int(input('Anna kolmas luku: '))
# Tulostetaan lukujen summa, tulo ja keskiarvo
print (f'Lukujen summa on {luku1 + luku2 + luku3}, tulo {luku1 * luku2 * luku3} ja keskiarvo {(luku1 + luku2 + luku3) / 3}')